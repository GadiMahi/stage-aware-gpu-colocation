"""The paper's eight figures.

Every figure is generated by a function here and by nothing else. When a number
changes, one command regenerates all of them; no figure is ever produced by hand
in a spreadsheet. That discipline is what makes revising an evaluation in
October survivable.

F1  Campaign GPU timeline with idle regions shaded       motivation
F2  Reported utilisation vs achieved occupancy           contribution 3
F3  System architecture                                  design
F4  Workload signatures on the occupancy/bandwidth plane workload selection
F5  Measured slowdown heatmap, all pairings              the dataset
F6  Predicted vs actual slowdown + feature ablation      the model
F7  Throughput against slowdown-bound violations         headline result
F8  Achieved occupancy by policy                         why throughput moved
"""
from __future__ import annotations

from pathlib import Path
from typing import List, Optional

import matplotlib.patches as mpatches
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from ..workloads import registry
from . import style

OUT_DIR = Path("figures")


def _save(fig, name: str, out_dir: Path = OUT_DIR) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    # reserve a strip at the bottom so the provenance footer cannot collide with
    # an axis label; tight_layout alone does not know the footer exists
    try:
        fig.tight_layout(rect=(0, 0.055, 1, 1))
    except Exception:  # noqa: BLE001
        pass
    path = out_dir / f"{name}.png"
    fig.savefig(path)
    fig.savefig(out_dir / f"{name}.pdf")
    plt.close(fig)
    return path


# ---------------------------------------------------------------------------
# F1 -- the motivating picture
# ---------------------------------------------------------------------------
def f1_campaign_timeline(trace, kind: str, out_dir: Path = OUT_DIR,
                         max_pipelines: int = 8) -> Path:
    """GPU occupancy over a campaign, with held-but-idle regions shaded.

    A Gantt-style timeline because the data's job is to show WHEN the device was
    held versus when it was used; a bar chart of totals would hide exactly the
    structure that motivates the project.
    """
    style.apply()
    df = trace.stages.copy()
    df = df[df["pipeline_id"] < max_pipelines]
    fig, ax = plt.subplots(figsize=style.TWO_COL_TALL)

    occ_of = {w: registry.get(w).sim_occupancy for w in df["workload"].unique()}
    cmap = plt.get_cmap(style.SEQUENTIAL)

    for pid, grp in df.groupby("pipeline_id"):
        grp = grp.sort_values("stage_idx")
        start = pd.to_numeric(grp["start_s"], errors="coerce").min()
        end = pd.to_numeric(grp["end_s"], errors="coerce").max()
        if np.isnan(start) or np.isnan(end):
            continue
        ax.add_patch(mpatches.Rectangle(
            (start, pid - 0.42), end - start, 0.84, facecolor="#f0f0f0",
            edgecolor="#cfcfcf", linewidth=0.5, zorder=1))
        for _, r in grp.iterrows():
            s, e = r["start_s"], r["end_s"]
            occ = occ_of.get(r["workload"], 0.0)
            if pd.isna(s) or pd.isna(e) or not r["gpu"] or occ <= 0:
                continue
            ax.add_patch(mpatches.Rectangle(
                (s, pid - 0.42), e - s, 0.84, facecolor=cmap(0.25 + 0.7 * occ),
                edgecolor="white", linewidth=0.4, zorder=2))

    n_rows = min(max_pipelines, df["pipeline_id"].nunique())
    ax.set_xlim(0, float(pd.to_numeric(df["end_s"], errors="coerce").max()) * 1.02)
    ax.set_ylim(-0.7, n_rows - 0.3)
    ax.set_xlabel("campaign time (s)")
    ax.set_ylabel("pipeline instance")
    ax.set_yticks(range(n_rows))
    ax.grid(axis="y", visible=False)

    idle = trace.held_but_idle_fraction * 100
    under = trace.held_but_under_occupied_fraction * 100
    ax.set_title(f"GPU held for the whole pipeline, used by part of it\n"
                 f"held but idle {idle:.1f}%   ·   held but under-occupied {under:.1f}%",
                 loc="left", color=style.INK)
    ax.legend(handles=[
        mpatches.Patch(facecolor="#f0f0f0", edgecolor="#cfcfcf", label="device held"),
        mpatches.Patch(facecolor=cmap(0.35), label="GPU work, low occupancy"),
        mpatches.Patch(facecolor=cmap(0.85), label="GPU work, high occupancy"),
    ], loc="upper right", ncol=3, fontsize=6)
    style.footer(fig, kind, f"policy={trace.policy}")
    return _save(fig, "f1_campaign_timeline", out_dir)


# ---------------------------------------------------------------------------
# F2 -- utilisation overstates occupancy
# ---------------------------------------------------------------------------
def f2_utilisation_vs_occupancy(signatures: pd.DataFrame, kind: str,
                                out_dir: Path = OUT_DIR) -> Path:
    """Paired bars: what nvidia-smi reports against what the device achieved.

    Two measures of the same quantity on one axis, so a paired bar is right and
    a dual axis would be wrong.
    """
    style.apply()
    df = signatures[["workload", "util_gpu_mean", "sm_occupancy_mean"]].dropna()
    df = df.sort_values("sm_occupancy_mean")

    y = np.arange(len(df))
    h = 0.38
    fig, ax = plt.subplots(figsize=(style.TWO_COL[0], 0.3 * len(df) + 1.4))
    ax.barh(y + h / 2 + 0.01, df["util_gpu_mean"], height=h,
            color=style.PALETTE[3], label="reported utilisation")
    ax.barh(y - h / 2 - 0.01, df["sm_occupancy_mean"], height=h,
            color=style.PALETTE[0], label="achieved occupancy")

    for i, (_, r) in enumerate(df.iterrows()):
        if r["sm_occupancy_mean"] > 0:
            ratio = r["util_gpu_mean"] / r["sm_occupancy_mean"]
            ax.text(max(r["util_gpu_mean"], r["sm_occupancy_mean"]) + 0.015, i,
                    f"{ratio:.1f}x", va="center", fontsize=6, color=style.MUTED)

    ax.set_yticks(y)
    ax.set_yticklabels(df["workload"], fontsize=6.5)
    ax.set_xlabel("fraction of peak")
    ax.set_xlim(0, 1.22)
    ax.grid(axis="y", visible=False)
    # The legend sits above the axes: every bar reaches toward x=1.0 and the
    # overstatement labels occupy the right margin, so there is no free corner
    # inside the plot area.
    ax.legend(loc="lower center", bbox_to_anchor=(0.5, 1.005), ncol=2, fontsize=6.5)
    ratios = (df["util_gpu_mean"] / df["sm_occupancy_mean"].replace(0, np.nan)).dropna()
    ax.set_title("Reported utilisation overstates achieved occupancy\n"
                 f"median overstatement {ratios.median():.1f}x, worst {ratios.max():.1f}x",
                 loc="left", color=style.INK, pad=22)
    style.footer(fig, kind)
    return _save(fig, "f2_utilisation_vs_occupancy", out_dir)


