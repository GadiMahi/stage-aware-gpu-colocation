# F4 -- workload spread
# ---------------------------------------------------------------------------
def f4_roofline_plane(signatures: pd.DataFrame, kind: str,
                      out_dir: Path = OUT_DIR) -> Path:
    """Where each workload sits on the occupancy / bandwidth plane.

    Evidence that the zoo was selected deliberately rather than conveniently,
    which reviewers reward.
    """
    style.apply()
    fig, ax = plt.subplots(figsize=style.ONE_COL_TALL)

    fams = sorted({registry.get(w).family for w in signatures["workload"]
                   if w in registry.ALL})
    fam_color = {f: style.PALETTE[i % len(style.PALETTE)] for i, f in enumerate(fams)}

    for _, r in signatures.iterrows():
        w = r["workload"]
        if w not in registry.ALL:
            continue
        spec = registry.get(w)
        x = r.get("sm_occupancy_mean", spec.sim_occupancy)
        y = r.get("dram_active_mean", spec.sim_dram_bw)
        size = 14 + 26 * (spec.sim_vram_mb / 12000.0)
        ax.scatter(x, y, s=size, color=fam_color[spec.family],
                   edgecolor="white", linewidth=0.6, zorder=3)
        ax.annotate(w.replace("_infer", "").replace("_", " ")[:14], (x, y),
                    textcoords="offset points", xytext=(4, 3),
                    fontsize=5.2, color=style.MUTED)

    ax.set_xlabel("achieved occupancy")
    ax.set_ylabel("DRAM activity")
    ax.set_xlim(0, 0.9)
    ax.set_ylim(0, 0.8)
    ax.legend(handles=[plt.Line2D([], [], marker="o", linestyle="", color=c,
                                  markersize=4, label=f)
                       for f, c in fam_color.items()],
              loc="upper left", fontsize=5.5, ncol=2)
    ax.set_title("Workload zoo spans the plane\n(marker size = VRAM footprint)",
                 loc="left", color=style.INK)
    style.footer(fig, kind)
    return _save(fig, "f4_roofline_plane", out_dir)


