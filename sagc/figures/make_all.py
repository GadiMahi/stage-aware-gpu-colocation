# F6 -- model quality
# ---------------------------------------------------------------------------
def f6_predicted_vs_actual(cv_predictions: pd.DataFrame,
                           a1_table: Optional[pd.DataFrame], kind: str,
                           out_dir: Path = OUT_DIR) -> Path:
    """Left: held-out predicted vs actual. Right: feature-set ablation."""
    style.apply()
    fig, axes = plt.subplots(1, 2, figsize=(style.TWO_COL[0], 2.8),
                             gridspec_kw={"width_ratios": [1.25, 1]})

    ax = axes[0]
    x = cv_predictions["y_true"].values
    y = cv_predictions["y_pred"].values
    lo, hi = float(min(x.min(), y.min())) - 0.02, float(max(x.max(), y.max())) + 0.02
    ax.plot([lo, hi], [lo, hi], color=style.MUTED, linewidth=0.8,
            linestyle="--", zorder=1)
    ax.scatter(x, y, s=7, color=style.PALETTE[0], alpha=0.45,
               edgecolor="none", zorder=2)
    ax.set_xlabel("measured slowdown")
    ax.set_ylabel("predicted slowdown")
    ax.set_xlim(lo, hi)
    ax.set_ylim(lo, hi)
    ax.set_title(f"Held-out workloads\nMAE {float(np.mean(np.abs(x - y))):.3f}",
                 loc="left", color=style.INK)

    ax2 = axes[1]
    if a1_table is not None and not a1_table.empty:
        t = a1_table.sort_values("mae")
        colors = [style.PALETTE[3] if f == "utilisation" else style.PALETTE[0]
                  for f in t["feature_set"]]
        ax2.barh(range(len(t)), t["mae"], color=colors, height=0.55)
        ax2.set_yticks(range(len(t)))
        ax2.set_yticklabels(t["feature_set"], fontsize=6.5)
        ax2.set_xlabel("leave-one-workload-out MAE")
        ax2.grid(axis="y", visible=False)
        for i, (_, r) in enumerate(t.iterrows()):
            ax2.text(r["mae"] * 1.02, i, f"{r['mae']:.3f}", va="center",
                     fontsize=6, color=style.MUTED)
        ax2.set_xlim(0, float(t["mae"].max()) * 1.32)
        ax2.set_title("Feature set (A1)", loc="left", color=style.INK)
    else:
        ax2.set_axis_off()

    fig.tight_layout()
    style.footer(fig, kind)
    return _save(fig, "f6_predicted_vs_actual", out_dir)


# ---------------------------------------------------------------------------
# F7 -- the headline
# ---------------------------------------------------------------------------
def f7_throughput_vs_violations(summary: pd.DataFrame, kind: str,
                                out_dir: Path = OUT_DIR) -> Path:
    """Throughput against bound violations. Up and to the left is better."""
    style.apply()
    fig, ax = plt.subplots(figsize=(4.2, 3.2))

    # The three predictive policies frequently land on exactly zero violations,
    # so without a dodge the last one drawn hides the others entirely. Offsets
    # are cosmetic and stated on the figure.
    dodge = {"utilisation": -0.55, "greedy": 0.0, "oracle": 0.55}
    marks = {"utilisation": "^", "greedy": "o", "oracle": "v"}
    dashes = {"utilisation": (3, 2), "greedy": (), "oracle": (1, 1.5)}
    overlapped = False

    for policy in ["exclusive", "blind", "utilisation", "greedy", "oracle"]:
        sub = summary[summary["policy"] == policy]
        if sub.empty:
            continue
        c = style.color_policy(policy)
        if policy in ("exclusive", "blind"):
            ax.scatter(sub["violation_rate"] * 100, sub["throughput_per_hour"],
                       color=c, s=46, marker="D" if policy == "blind" else "s",
                       edgecolor="white", linewidth=0.7, zorder=5,
                       label=style.label_policy(policy))
        else:
            sub2 = sub.sort_values("throughput_per_hour")
            if sub2["violation_rate"].nunique() == 1:
                overlapped = True
            line, = ax.plot(sub2["violation_rate"].values * 100 + dodge[policy],
                            sub2["throughput_per_hour"].values, color=c,
                            marker=marks[policy], markersize=4, linewidth=1.3,
                            markeredgecolor="white", markeredgewidth=0.5,
                            zorder=4 if policy == "greedy" else 3,
                            label=style.label_policy(policy))
            if dashes[policy]:
                line.set_dashes(dashes[policy])

    ax.set_xlabel("slowdown-bound violations (% of stages)")
    ax.set_ylabel("throughput (pipelines / hour)")
    ax.set_xlim(-3, max(72, float(summary["violation_rate"].max()) * 100 + 6))
    ax.legend(loc="center right", fontsize=6.2)
    ax.set_title("More work done, fewer promises broken"
                 + ("\npredictive policies dodged horizontally where they coincide"
                    if overlapped else ""),
                 loc="left", color=style.INK, fontsize=8.5)
    style.footer(fig, kind)
    return _save(fig, "f7_throughput_vs_violations", out_dir)


# ---------------------------------------------------------------------------
# F8 -- why throughput moved
# ---------------------------------------------------------------------------
def f8_occupancy_by_policy(summary: pd.DataFrame, kind: str,
                           out_dir: Path = OUT_DIR,
                           bound: Optional[float] = 1.25) -> Path:
    """Achieved occupancy per policy: the mechanism behind the throughput gain."""
    style.apply()
    rows = []
    for policy in ["exclusive", "blind", "utilisation", "greedy", "oracle"]:
        sub = summary[summary["policy"] == policy]
        if sub.empty:
            continue
        if policy in ("greedy", "utilisation", "oracle") and bound is not None:
            pick = sub[np.isclose(sub["slowdown_bound"], bound)]
            sub = pick if not pick.empty else sub
        rows.append({"policy": policy,
                     "occupancy": sub.iloc[0]["mean_achieved_occupancy"]})
    t = pd.DataFrame(rows)

    fig, ax = plt.subplots(figsize=style.ONE_COL)
    xs = np.arange(len(t))
    ax.bar(xs, t["occupancy"], color=[style.color_policy(p) for p in t["policy"]],
           width=0.6)
    for i, v in enumerate(t["occupancy"]):
        ax.text(i, v + 0.015, f"{v:.2f}", ha="center", fontsize=6.5, color=style.MUTED)
    ax.set_xticks(xs)
    ax.set_xticklabels([style.label_policy(p).split(" (")[0] for p in t["policy"]],
                       rotation=20, ha="right", fontsize=6.5)
    ax.set_ylabel("time-weighted achieved occupancy")
    ax.set_ylim(0, max(float(t["occupancy"].max()) * 1.25, 0.2))
    ax.grid(axis="x", visible=False)
    ax.set_title(f"Achieved occupancy (bound {bound})", loc="left", color=style.INK)
    style.footer(fig, kind)
    return _save(fig, "f8_occupancy_by_policy", out_dir)


def make_all(trace, signatures: pd.DataFrame, pairs: pd.DataFrame,
             cv_predictions: pd.DataFrame, a1_table: Optional[pd.DataFrame],
             summary: pd.DataFrame, kind: str, out_dir: Path = OUT_DIR,
             verbose: bool = True) -> List[Path]:
    """Regenerate every figure. One command, no manual steps."""
    made: List[Path] = []
    jobs = [
        ("F1", lambda: f1_campaign_timeline(trace, kind, out_dir)),
        ("F2", lambda: f2_utilisation_vs_occupancy(signatures, kind, out_dir)),
        ("F3", lambda: f3_architecture(out_dir)),
        ("F4", lambda: f4_roofline_plane(signatures, kind, out_dir)),
        ("F5", lambda: f5_slowdown_heatmap(pairs, kind, out_dir)),
        ("F6", lambda: f6_predicted_vs_actual(cv_predictions, a1_table, kind, out_dir)),
        ("F7", lambda: f7_throughput_vs_violations(summary, kind, out_dir)),
        ("F8", lambda: f8_occupancy_by_policy(summary, kind, out_dir)),
    ]
    for tag, fn in jobs:
        try:
            p = fn()
            made.append(p)
            if verbose:
                print(f"  {tag}  {p}")
        except Exception as exc:  # noqa: BLE001
            if verbose:
                print(f"  {tag}  FAILED: {type(exc).__name__}: {exc}")
    return made
