# F5 -- slowdown heatmap
# ---------------------------------------------------------------------------
def f5_slowdown_heatmap(pairs: pd.DataFrame, kind: str, out_dir: Path = OUT_DIR,
                        thread_pct: int = 100) -> Path:
    """Every pairing's measured slowdown. Sequential ramp, single hue."""
    style.apply()
    df = pairs[pairs["thread_pct_a"] == thread_pct].copy()
    names = sorted(set(df["workload_a"]) | set(df["workload_b"]))
    idx = {n: i for i, n in enumerate(names)}
    M = np.full((len(names), len(names)), np.nan)
    OOM = np.zeros_like(M, dtype=bool)

    for (a, b), grp in df.groupby(["workload_a", "workload_b"]):
        i, j = idx[a], idx[b]
        if grp["oom"].astype(bool).all():
            OOM[i, j] = True
            continue
        vals = pd.to_numeric(grp["slowdown_a"], errors="coerce").dropna()
        if not vals.empty:
            M[i, j] = vals.median()

    fig, ax = plt.subplots(figsize=(5.0, 4.4))
    vmax = np.nanpercentile(M, 99) if np.isfinite(M).any() else 2.0
    im = ax.imshow(M, cmap=style.SEQUENTIAL, vmin=1.0, vmax=max(vmax, 1.05),
                   aspect="auto")

    for i in range(len(names)):
        for j in range(len(names)):
            if OOM[i, j]:
                ax.add_patch(mpatches.Rectangle(
                    (j - 0.5, i - 0.5), 1, 1, facecolor="#3a3a3a",
                    edgecolor="white", linewidth=0.4))
                ax.text(j, i, "x", ha="center", va="center", fontsize=6, color="white")

    ax.set_xticks(range(len(names)))
    ax.set_yticks(range(len(names)))
    ax.set_xticklabels([n[:16] for n in names], rotation=60, ha="right", fontsize=5.5)
    ax.set_yticklabels([n[:16] for n in names], fontsize=5.5)
    ax.set_xlabel("co-tenant")
    ax.set_ylabel("target workload (the one being slowed)")
    ax.grid(visible=False)
    cb = fig.colorbar(im, ax=ax, fraction=0.042, pad=0.03)
    cb.set_label("slowdown (co-located / solo)", fontsize=7)
    cb.ax.tick_params(labelsize=6)
    ax.set_title(f"Measured pairwise slowdown at {thread_pct}% partition\n"
                 f"dark cells: VRAM exhaustion ({int(OOM.sum())} pairings)",
                 loc="left", color=style.INK)
    style.footer(fig, kind)
    return _save(fig, "f5_slowdown_heatmap", out_dir)


