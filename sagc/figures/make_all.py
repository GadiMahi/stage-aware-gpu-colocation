# F3 -- architecture
# ---------------------------------------------------------------------------
def f3_architecture(out_dir: Path = OUT_DIR) -> Path:
    """Module diagram. A schematic, so no provenance question arises."""
    style.apply()
    fig, ax = plt.subplots(figsize=(style.TWO_COL[0], 3.6))
    ax.set_axis_off()
    ax.set_xlim(0, 10)
    ax.set_ylim(0, 10)

    def box(x, y, w, h, title, sub, fc="#ffffff"):
        ax.add_patch(mpatches.FancyBboxPatch(
            (x, y), w, h, boxstyle="round,pad=0.06,rounding_size=0.12",
            facecolor=fc, edgecolor=style.INK, linewidth=0.8))
        ax.text(x + w / 2, y + h * 0.62, title, ha="center", va="center",
                fontsize=7.5, fontweight="bold", color=style.INK)
        ax.text(x + w / 2, y + h * 0.26, sub, ha="center", va="center",
                fontsize=6, color=style.MUTED)

    def arrow(x1, y1, x2, y2):
        ax.annotate("", xy=(x2, y2), xytext=(x1, y1),
                    arrowprops=dict(arrowstyle="-|>", color=style.MUTED,
                                    linewidth=0.8, shrinkA=2, shrinkB=2))

    box(0.3, 8.2, 9.4, 1.2, "M6  Evaluation harness and trace-driven simulator",
        "campaign-scale replay, validated against hardware", fc="#f7f7f7")
    box(0.3, 5.6, 2.9, 1.9, "M1  Pipeline executor",
        "four-stage DAG\nN concurrent instances")
    box(3.6, 5.6, 2.8, 1.9, "M5  Stage-aware scheduler",
        "greedy under bound\nILP gap, bandit")
    box(6.8, 5.6, 2.9, 1.9, "M4  Slowdown predictor",
        "GBM, leave-one-out\nprecomputed table")
    box(6.8, 3.0, 2.9, 1.7, "M3  Pair dataset",
        "78 pairings under MPS\nOOM as an outcome")
    box(3.6, 3.0, 2.8, 1.7, "MPS control plane",
        "daemon, thread %\n(mechanism, not policy)", fc="#f2f2f2")
    box(0.3, 3.0, 2.9, 1.7, "M2  Counter profiler",
        "DCGM 100 ms\n18-feature signature")
    box(2.2, 0.8, 5.6, 1.3, "2 x NVIDIA T4 on one node", "16 GB each", fc="#ececec")

    for a in [(1.75, 5.6, 1.75, 4.7), (5.0, 5.6, 5.0, 4.7), (8.25, 5.6, 8.25, 4.7),
              (6.8, 6.55, 6.4, 6.55), (3.6, 6.55, 3.2, 6.55),
              (8.25, 3.0, 8.25, 2.1), (5.0, 3.0, 5.0, 2.1), (1.75, 3.0, 1.75, 2.1),
              (5.0, 8.2, 5.0, 7.5)]:
        arrow(*a)

    ax.set_title("Stage-aware GPU co-location: module architecture",
                 loc="left", color=style.INK, fontsize=9)
    return _save(fig, "f3_architecture", out_dir)


